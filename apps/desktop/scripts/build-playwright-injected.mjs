// Lifts Playwright's injected script out of playwright-core at build time so
// the packaged app carries the ~307 KB text and not the 10 MB package. The
// bundle stores the script as a single string literal (`source3 = "…"`), so the
// literal is sliced out and evaluated once here instead of on every install.
import * as NodeFSP from "node:fs/promises";
import * as NodeModule from "node:module";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";
import * as NodeVM from "node:vm";

const MARKER = "source3 = ";
const TERMINATOR = ";\n  }\n});";
const MINIMUM_LENGTH = 100_000;
const EVALUATION_TIMEOUT_MS = 1_000;

const directory = NodePath.dirname(NodeURL.fileURLToPath(import.meta.url));
const appRoot = NodePath.join(directory, "..");
const outputPath = NodePath.join(
  appRoot,
  "src",
  "preview",
  "PlaywrightInjectedSource.generated.ts",
);
const require = NodeModule.createRequire(import.meta.url);
const bundlePath = NodePath.join(
  NodePath.dirname(require.resolve("playwright-core/package.json")),
  "lib/coreBundle.js",
);

const coreBundle = await NodeFSP.readFile(bundlePath, "utf8");
const literalStart = coreBundle.indexOf(MARKER);
if (literalStart < 0) {
  throw new Error(`Playwright injected runtime marker ${MARKER} was not found in ${bundlePath}`);
}
const literalEnd = coreBundle.indexOf(TERMINATOR, literalStart + MARKER.length);
if (literalEnd < 0) {
  throw new Error(
    `Playwright injected runtime terminator ${JSON.stringify(TERMINATOR)} was not found in ${bundlePath}`,
  );
}

const source = NodeVM.runInNewContext(
  coreBundle.slice(literalStart + MARKER.length, literalEnd),
  Object.create(null),
  { timeout: EVALUATION_TIMEOUT_MS },
);
if (typeof source !== "string" || source.length < MINIMUM_LENGTH) {
  throw new Error(
    `Playwright injected runtime from ${bundlePath} was ${typeof source}${
      typeof source === "string" ? ` with ${source.length} characters` : ""
    }; expected a string with at least ${MINIMUM_LENGTH} characters`,
  );
}
if (!source.includes("InjectedScript")) {
  throw new Error(`Playwright injected runtime from ${bundlePath} does not define InjectedScript`);
}

// Single-quoted with escapes chosen by hand: the script is full of double
// quotes, so this is the literal the repo formatter would settle on anyway and
// the generated file passes `vp fmt --check` without a second pass.
const encodedSource = `'${source
  .replaceAll("\\", "\\\\")
  .replaceAll("'", "\\'")
  .replaceAll("\r", "\\r")
  .replaceAll("\n", "\\n")
  .replaceAll("\u2028", "\\u2028")
  .replaceAll("\u2029", "\\u2029")}'`;

await NodeFSP.writeFile(
  outputPath,
  `// Generated by scripts/build-playwright-injected.mjs. Do not edit.\nexport const playwrightInjectedSource =\n  ${encodedSource};\n`,
);
