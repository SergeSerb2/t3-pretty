/**
 * Built-in catalog of remote MCP servers users can connect as Apps. Every
 * entry was probed live for a Streamable HTTP endpoint (POST initialize →
 * 200, or 401 with an RFC 9728 bearer challenge). Servers that only speak
 * the legacy SSE transport are deliberately absent.
 *
 * Data only — no runtime logic. Clients render it; the server uses `auth`,
 * `scopes`, `authorizeParams`, and `oauthClientFamily` when authorizing.
 *
 * @module appsCatalog
 */
