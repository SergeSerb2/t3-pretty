export interface AppCatalogEntry {
  /** Stable id; doubles as the default slug. */
  readonly id: string;
  readonly name: string;
  readonly description: string;
  readonly category: AppCategory;
  /** Streamable HTTP MCP endpoint. */
  readonly url: string;
  /** Default auth kind. */
  readonly auth: AppAuthKind;
  /**
   * Set when the authorization server has no dynamic client registration and
   * the user must bring their own OAuth client (see `APP_OAUTH_CLIENT_FAMILIES`).
   */
  readonly oauthClientFamily?: string;
  /** Default OAuth scopes (space-separated); empty = let the server decide. */
  readonly scopes?: string;
  /** Extra authorize-request params (e.g. Google offline access). */
  readonly authorizeParams?: Readonly<Record<string, string>>;
  /** `token` auth is also accepted (PAT / API key) — offered as an alternative. */
  readonly tokenSupported?: boolean;
  /** Header for `token` auth when it isn't `Authorization: Bearer`. */
  readonly tokenHeader?: string;
  /** Where to mint a token / API key. */
  readonly tokenHelpUrl?: string;
  /** Domain whose favicon represents the brand. */
  readonly iconDomain: string;
  /** Monogram background when the favicon can't load. */
  readonly color: string;
}

export interface AppOAuthClientFamily {
  readonly id: string;
  readonly name: string;
  /** Where to create the OAuth client. */
  readonly consoleUrl: string;
  /** Short, ordered setup steps shown next to the Client ID / Secret fields. */
  readonly steps: ReadonlyArray<string>;
}

